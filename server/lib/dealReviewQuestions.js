//   customerVoice -- only the customer saying it counts ("in their words",
//               "unprompted", "did the customer validate"). The evidence-based
//               fill won't mark these answered without a customer speaker.
//
// Section flags:
//   killer   -- inverted polarity: each item is a red flag that is either
//               present or clear, not a question that is answered or not.

