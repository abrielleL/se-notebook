// Flatten into { section, key, text, ... } with stable keys: `<section>.h` for
// the headline and `<section>.<n>` for the n-th deeper question (1-based).
const SECTIONS = RAW.map((s, i) => ({
  key: s.key,
  number: i + 1,
  title: s.title,
  killer: !!s.killer,
  applies: s.applies || null,
  questions: [
    { key: `${s.key}.h`, text: s.headline, headline: true, manual: !!s.manual, applies: s.applies || null,
      customerVoice: !!s.headlineCustomerVoice },
    ...s.deeper.map((d, n) => ({
      key: `${s.key}.${n + 1}`,
      text: d.q,
      headline: false,
      manual: !!d.manual,
      computed: d.computed || null,
      applies: d.applies || s.applies || null,
      customerVoice: !!d.customerVoice
    }))
  ]
}));

const QUESTIONS = SECTIONS.flatMap(s => s.questions.map(q => ({ ...q, section: s.key, killer: s.killer })));
const BY_KEY = new Map(QUESTIONS.map(q => [q.key, q]));

// Answered/partial/unanswered/na for ordinary questions; flagged/clear for
// the deal-killer items, where "flagged" means the risk is present.
const STATUSES = ['answered', 'partial', 'unanswered', 'na', 'flagged', 'clear'];
// Whose words the answer rests on. 'team' is the AE/SE's own read, e.g. from
// an internal call; it never counts as the customer having said it.
// 'app' = taken from the notebook's own records (contacts, next steps, history).
const VOICES = ['customer', 'team', 'inferred', 'app'];

module.exports = { SECTIONS, QUESTIONS, BY_KEY, STATUSES, VOICES, APPLIES_LABEL };
